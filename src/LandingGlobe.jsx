// Project lon/lat → SVG viewBox coords
// Center: lon=65 (Gulf centered), lat offset=20 (vertical center), scale=280
function project(lat, lon) {
  const x = 50 + ((lon - 65) / 360) * 280;
  const y = 50 - ((lat - 20) / 180) * 280;
  return { x, y };
}

